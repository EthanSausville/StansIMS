"""Turn the exported workbook JSON into supabase/seed.sql.

Usage:
  python3 tools/excel_export.py Stans.xlsm tests/fixtures/workbook.json
  python3 tools/make_seed.py tests/fixtures/workbook.json supabase/seed.sql

The seed is safe to run more than once: keyed rows are skipped if they already
exist, and sales are only loaded into an empty sales table.
"""
import json, sys

data = json.load(open(sys.argv[1]))['inputs']
out = []

def lit(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def insert(table, rows, cols, conflict='do nothing', key=None):
    if not rows: return
    out.append(f'insert into public.{table} ({", ".join(cols)}) values')
    out.append(',\n'.join('  (' + ', '.join(lit(r.get(c)) for c in cols) + ')' for r in rows))
    out.append(f'on conflict {("(" + key + ") ") if key else ""}{conflict};\n')

out.append('-- Generated by tools/make_seed.py from Stans.xlsm. Run after schema.sql.\nbegin;\n')
insert('items', data['items'], ['item_no', 'name', 'type', 'unit', 'pack_note', 'sort'])
insert('standard_costs', data['standard_costs'], ['item_no', 'year', 'cost'])
insert('standard_prices', data['standard_prices'], ['item_no', 'year', 'price'])
insert('recipes', data['recipes'], ['item_no', 'name', 'batch_size'])
s = dict(data['settings'], id=1)
insert('settings', [s], ['id'] + list(data['settings'].keys()))
insert('year_settings', data['year_settings'], ['year', 'labor_scenario'])
insert('purchase_settings', data['purchase_settings'],
       ['item_no', 'avg_weekly', 'max_weekly', 'manual_usage', 'standard_purchase', 'lead_time', 'safety_threshold'])

# Lines have no natural key, so only load them when the table is empty.
for table, rows, cols in [('recipe_lines', data['recipe_lines'], ['recipe_item_no', 'item_no', 'qty', 'uses_batch_minutes', 'sort']),
                          ('fg_lines', data['fg_lines'], ['fg_item_no', 'item_no', 'qty', 'sort']),
                          ('sales', data['sales'], ['date', 'invoice', 'quantity', 'price', 'amount', 'customer', 'product', 'item_no'])]:
    casts = {'date': 'date', 'quantity': 'numeric', 'price': 'numeric', 'amount': 'numeric', 'qty': 'numeric',
             'item_no': 'int', 'recipe_item_no': 'int', 'fg_item_no': 'int', 'sort': 'int',
             'uses_batch_minutes': 'boolean', 'invoice': 'text', 'customer': 'text', 'product': 'text'}
    # The first row carries explicit types so Postgres knows each column's type
    # even when a column happens to be null in the first rows.
    lines = ['  (' + ', '.join(f'{lit(rows[0].get(c))}::{casts[c]}' for c in cols) + ')']
    lines += ['  (' + ', '.join(lit(r.get(c)) for c in cols) + ')' for r in rows[1:]]
    out.append(f'insert into public.{table} ({", ".join(cols)})\nselect * from (values')
    out.append(',\n'.join(lines))
    out.append(f') as v ({", ".join(cols)})\nwhere not exists (select 1 from public.{table});\n')

insert('production', [dict(r, cases=r['cases']) for r in data['production']], ['date', 'item_no', 'cases'])
insert('goods_receipts', data['goods_receipts'], ['date', 'item_no', 'qty'])
insert('cycle_counts', data['cycle_counts'], ['date', 'item_no', 'qty'])
out.append('commit;\n')
open(sys.argv[2], 'w').write('\n'.join(out))
print('wrote', sys.argv[2])
